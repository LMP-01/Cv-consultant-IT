export function getSpecies(id: number): Species {
  const found = SPECIES.find((s) => s.id === id);
  if (!found) throw new Error(`Unknown species id: ${id}`);
  return found;
}

export function getSpeciesByName(name: string): Species | undefined {
  return SPECIES.find((s) => s.name.toLowerCase() === name.toLowerCase());
}
